"""Porta in pokeplatinum le animazioni delle mosse 468+ di hg-engine (armips/move/move_anim/*.s).

Platinum e HGSS hanno gli stessi comandi di animazione 0-84 (HGSS ne aggiunge 85-87, hg-engine 88
= changepermanentbg) e le stesse funzioni (CallFunc 0-83, stessi argomenti): uno script di hg-engine
si traduce parola per parola. Lo script:
  - espande le macro armips di hg-engine (armips/include/animscriptcmd.s) in parole .long, con la
    riga originale come commento;
  - rinumera le particelle (SPA): HGSS ha un file in più all'indice 31; le 59 nuove di hg-engine
    (rawdata/move_spa/9_486..544) sono copiate in res/graphics/battle/particles/hg_engine_NNN.spa
    e accodate a battle_particles.order;
  - rinumera i suoni per nome (SDAT di HGSS -> pl_sound_data.json);
  - toglie changepermanentbg (lo sfondo dei terreni lo cambia lo script di lotta);
  - lascia il segnaposto alle mosse che usano comandi o sfondi che Platinum non ha.
Scrive solo anim.s ancora segnaposto ("@ PLACEHOLDER") o già generati ("@ PORTED"): per tenere
una modifica a mano basta togliere la prima riga. Rieseguibile. Uso: python3 -I port_move_anims.py
"""
import collections, hashlib, json, os, re, shutil, struct, sys

sys.path.insert(0, os.path.dirname(__file__))
import hg_parse

HG = hg_parse.HG
PP = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PORTED = '@ PORTED: generated by tools/expansion/port_move_anims.py'
PLACEHOLDER = '@ PLACEHOLDER'
FIRST_NEW_MOVE = 468          # Hone Claws: da qui l'ID hg-engine è ufficiale + 3
HG_OFFSET = 3
PARTICLES = f'{PP}/res/graphics/battle/particles'
VANILLA_PARTICLES = 485       # file vanilla di battle_particles.order (0-484)
HG_FIRST_NEW_PARTICLE = 486
HG_ONLY_PARTICLE = 31         # file di HGSS che Platinum non ha
MAX_PT_ANIM_BG = 57           # sBgNarcIndices di battle_anim_system.c: sfondi 0-57
MAX_PT_ANIM_CMD = 0x54

log = collections.defaultdict(list)


def read(path):
    return open(path, encoding='utf-8', errors='replace').read()


def write(path, text):
    if not os.path.exists(path) or read(path) != text:
        open(path, 'w', encoding='utf-8', newline='\n').write(text)


# ---------------------------------------------------------------- macro armips di hg-engine
def parse_macros(path):
    macros = {}
    cur = None
    for line in read(path).split('\n'):
        line = line.split('//')[0].strip()
        if not line:
            continue
        m = re.match(r'\.macro\s+(\w+)\s*,?\s*(.*)', line)
        if m:
            cur = (m.group(1), [p.strip() for p in m.group(2).split(',') if p.strip()], [])
            continue
        if line == '.endmacro':
            macros[cur[0]] = (cur[1], cur[2])
            cur = None
            continue
        if cur:
            cur[2].append(line)
    return macros


MACROS = parse_macros(f'{HG}/armips/include/animscriptcmd.s')

# costanti armips (.equ NOME, valore) degli include di hg-engine
GLOBAL_EQU = {}
for inc in sorted(os.listdir(f'{HG}/armips/include')):
    if inc.endswith('.s'):
        text = read(f'{HG}/armips/include/{inc}')
        for m in re.finditer(r'^\s*\.equ\s+(\w+)\s*,\s*([^/\n]+)', text, flags=re.M):
            GLOBAL_EQU.setdefault(m.group(1), m.group(2).strip())
        for m in re.finditer(r'^\s*(\w+)\s+equ\s+([^/\n]+)', text, flags=re.M | re.I):
            GLOBAL_EQU.setdefault(m.group(1), m.group(2).strip())


def split_args(s):
    return [a.strip() for a in s.split(',')] if s.strip() else []


class Unsupported(Exception):
    pass


def subst(expr, env):
    return re.sub(r'\b\w+\b', lambda m: str(env.get(m.group(0), m.group(0))), expr)


def expand(name, args, remap):
    """Espande la macro in una lista di espressioni .long."""
    if name not in MACROS:
        raise Unsupported(f'macro {name}')
    params, body = MACROS[name]
    args = list(args) + ['0'] * (len(params) - len(args))
    args = remap(name, args)
    if args is None:
        return []
    env = dict(zip(params, args))
    out = []
    skip = []
    for line in body:
        if line.startswith('.if '):
            cond = subst(line[4:], env)
            try:
                skip.append(not eval(cond, {}, {}))
            except Exception:
                raise Unsupported(f'{name}: .if {cond}')
            continue
        if line == '.endif':
            skip.pop()
            continue
        if any(skip):
            continue
        if line.startswith('.word'):
            for w in split_args(line[5:]):
                w = subst(w, env)
                if 'NaN' in w:
                    raise Unsupported(f'{name}: NaN')
                out.append(w)
            continue
        m = re.match(r'(\w+)\s*(.*)', line)
        out += expand(m.group(1), [subst(a, env) for a in split_args(m.group(2))], remap)
    return out


# ---------------------------------------------------------------- suoni
def sdat_seq_names(path):
    d = open(path, 'rb').read()
    symb_off, symb_size = struct.unpack_from('<II', d, 0x10)
    s = d[symb_off:symb_off + symb_size]
    rec = struct.unpack_from('<I', s, 8)[0]
    names = []
    for i in range(struct.unpack_from('<I', s, rec)[0]):
        o = struct.unpack_from('<I', s, rec + 4 + 4 * i)[0]
        names.append(s[o:s.index(b'\0', o)].decode() if o else '')
    return names


HG_SEQ = sdat_seq_names(f'{HG}/base/root/data/sound/gs_sound_data.sdat')
PT_SEQ = {e['name']: i for i, e in enumerate(json.load(open(f'{PP}/res/sound/pl_sound_data.json'))['seqInfo'])
          if e.get('name')}


def sound(value):
    n = int(value, 0)
    name = HG_SEQ[n] if n < len(HG_SEQ) else ''
    if name not in PT_SEQ:
        raise Unsupported(f'suono {n} ({name})')
    return str(PT_SEQ[name])


SOUND_MACROS = {'playse', 'playsepan', 'playsepanmod', 'repeatse', 'waitse', 'stopse'}


# ---------------------------------------------------------------- particelle
def particle(value):
    n = int(value, 0)
    if n < HG_ONLY_PARTICLE:
        return str(n)
    if n == HG_ONLY_PARTICLE:
        raise Unsupported('particella 31 di HGSS')
    if n < HG_FIRST_NEW_PARTICLE:
        return str(n - 1)
    return str(VANILLA_PARTICLES + n - HG_FIRST_NEW_PARTICLE)


def import_particles():
    order_path = f'{PARTICLES}/battle_particles.order'
    order = read(order_path).split()[:VANILLA_PARTICLES]
    meson = read(f'{PARTICLES}/meson.build')
    meson = re.sub(r"\n    'hg_engine_\d+\.spa',", '', meson)
    new = []
    for f in sorted(os.listdir(f'{HG}/rawdata/move_spa'), key=lambda f: int(f.split('_')[1])):
        n = int(f.split('_')[1])
        name = f'hg_engine_{n}.spa'
        assert len(order) == VANILLA_PARTICLES + n - HG_FIRST_NEW_PARTICLE, f
        shutil.copyfile(f'{HG}/rawdata/move_spa/{f}', f'{PARTICLES}/{name}')
        order.append(name)
        new.append(f"\n    '{name}',")
    meson = meson.replace("\n    'shadow_force.spa',", "\n    'shadow_force.spa'," + ''.join(new), 1)
    write(f'{PARTICLES}/meson.build', meson)
    write(order_path, '\n'.join(order) + '\n')
    return len(new)


# ---------------------------------------------------------------- traduzione
def remap(name, args):
    if name == 'changepermanentbg':
        return None
    if name == 'loadparticle':
        args[1] = particle(args[1])
    if name in SOUND_MACROS:
        args[0] = sound(args[0])
    if name in ('changebg', 'resetbg', 'changemonbg', 'resetmonbg'):
        if int(args[0], 0) > MAX_PT_ANIM_BG:
            raise Unsupported(f'sfondo di animazione {args[0]}')
    return args


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return [l.split('//')[0].rstrip() for l in text.split('\n')]


def translate(path):
    out = []
    equ = dict(GLOBAL_EQU)  # più le costanti "nome equ valore" definite nel file
    for raw in strip_comments(read(path)):
        line = raw.strip()
        if not line or line.startswith('.'):
            continue
        m = re.match(r'(\w+):$', line)
        if m:
            out.append(f'{m.group(1)}:')
            continue
        m = re.match(r'(\w+)\s+equ\s+(.+)', line, flags=re.I)
        if m:
            equ[m.group(1)] = m.group(2).strip()
            continue
        m = re.match(r'(\w+)\s*(.*)', line)
        args = split_args(m.group(2))
        for _ in range(4):  # costanti definite con altre costanti
            args = [subst(a, equ) for a in args]
        words = expand(m.group(1), args, remap)
        op = int(words[0], 0) if words and re.fullmatch(r'0x[0-9A-Fa-f]+|\d+', words[0]) else None
        if op is not None and op > MAX_PT_ANIM_CMD:
            raise Unsupported(f'comando 0x{op:X}')
        out.append(f'    @ {line}')
        out += [f'    .long {w}' for w in words]
    return out


# Segnaposto di hg-engine (le scintille di Hone Claws senza suono, usato da ~220 mosse): per queste
# resta il segnaposto di import_moves.py, che copia una mossa vanilla dello stesso tipo e classe.
HG_PLACEHOLDER_BODY = """loadparticlefromspa 0, 486
waitparticle
addparticle 0, 2, 3
addparticle 0, 1, 3
addparticle 0, 1, 3
addparticle 0, 0, 3
wait 10
addparticle 0, 1, 3
addparticle 0, 1, 3
wait 10
addparticle 0, 2, 3
addparticle 0, 0, 3
waitparticle
unloadparticle 0
waitstate
end"""


def hg_body(path):
    lines = [l.strip() for l in strip_comments(read(path))]
    return '\n'.join(l for l in lines if l and not l.startswith('.') and not re.match(r'\w+:$', l))


def main():
    log['particles'] = import_particles()
    moves = read(f'{PP}/generated/moves.txt').split()
    for move in range(FIRST_NEW_MOVE, len(moves)):
        if moves[move] == 'MOVE_NONE':
            continue
        folder = f'{PP}/res/moves/{moves[move][5:].lower()}'
        anim = f'{folder}/anim.s'
        src = f'{HG}/armips/move/move_anim/{move + HG_OFFSET:03d}.s'
        if not os.path.isdir(folder) or not os.path.exists(src):
            log['missing'].append(moves[move])
            continue
        text = read(anim) if os.path.exists(anim) else ''
        if text and PLACEHOLDER not in text and not text.startswith(PORTED):
            log['kept'].append(moves[move])
            continue
        if hg_body(src) == HG_PLACEHOLDER_BODY:
            log['hg_placeholder'].append(moves[move])
            if text.startswith(PORTED):
                log['to_restore'].append(anim)
            continue
        try:
            body = translate(src)
        except Unsupported as e:
            log['unsupported'].append(f'{moves[move]}: {e}')
            continue
        write(anim, f'{PORTED} from hg-engine move_anim/{move + HG_OFFSET:03d}.s\n'
                    '#include "macros/btlanimcmd.inc"\n\n' + '\n'.join(body) + '\n')
        log['ported'].append(moves[move])

    print(f"particelle nuove: {log['particles']}; animazioni portate: {len(log['ported'])}; "
          f"segnaposto anche in hg-engine: {len(log['hg_placeholder'])}; "
          f"tenute (scritte a mano): {len(log['kept'])}; mancanti: {len(log['missing'])}")
    for anim in log['to_restore']:
        print('  generata prima ma è un segnaposto di hg-engine: cancellala e rilancia import_moves.py:', anim)
    for u in log['unsupported']:
        print('  segnaposto:', u)
    for m in log['missing']:
        print('  mancante:', m)


main()
