"""Importa in pokeplatinum le mosse ufficiali 468..919 (Gen 5-9) da hg-engine.

Numerazione ufficiale: in hg-engine le mosse da Hone Claws in poi hanno ID = ufficiale + 3 (segnaposto 468-470).
Rieseguibile: riscrive la coda di generated/moves.txt e generated/move_battle_effects.txt, le cartelle
res/moves/<mossa>/ delle mosse nuove (data.json e script.s sempre; anim.s solo se manca o è un segnaposto)
e gli script degli effetti nuovi solo se mancano o sono ancora segnaposto.
Uso: python3 -I import_moves.py
"""
import collections, json, os, re, sys

sys.path.insert(0, os.path.dirname(__file__))
import hg_parse

PP = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HG = hg_parse.HG
FIRST_NEW, LAST_OFFICIAL, HG_SHIFT = 468, 919, 3
VANILLA_EFFECTS = 277                       # BATTLE_EFFECT 0..276 uguali (nome a parte) in hg-engine
PLACEHOLDER = "@ PLACEHOLDER: generated by tools/expansion/import_moves.py"
log = collections.defaultdict(list)


def lines(path):
    return open(os.path.join(PP, path)).read().split()


def write(path, text):
    full = os.path.join(PP, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    if not os.path.exists(full) or open(full, encoding='utf-8').read() != text:
        open(full, 'w', encoding='utf-8', newline='\n').write(text)


# ---------- testo ----------
CHARMAP = set()
for _l in open(os.path.join(PP, 'build/tools/msgenc/charmap.txt'), encoding='utf-8'):
    if '=' in _l:
        CHARMAP.add(_l.rstrip('\n').split('=', 1)[1])


def clean(text, where):
    text = text.replace("'", '’').replace('—', '-').replace('–', '-').replace('\\"', '"')
    out, quote = [], False
    for ch in text:
        if ch == '"':
            ch = '”' if quote else '“'
            quote = not quote
        if ch not in CHARMAP and ch != '\n':
            log['char_replaced'].append(f'{where}: {ch!r}')
            ch = '?'
        out.append(ch)
    return ''.join(out)


# ---------- hg-engine ----------
def move_entries():
    text = hg_parse._strip_comments(open(os.path.join(HG, 'data/Moves.c'), encoding='utf-8').read())
    out = {}
    for m in re.finditer(r'\[\s*(MOVE_\w+)\s*\]\s*=\s*\{', text):
        depth, j = 0, m.end() - 1
        while True:
            if text[j] == '{': depth += 1
            elif text[j] == '}':
                depth -= 1
                if depth == 0: break
            j += 1
        out[m.group(1)] = text[m.end():j]
    return out


CONFIG = hg_parse.constants('include/config.h', 'CHAMPIONS_')


def resolve(v):
    """((CHAMPIONS_X) ? (a) : (b)) -> a o b secondo include/config.h di hg-engine."""
    m = re.fullmatch(r'\(\(\s*(\w+)\s*\)\s*\?\s*\(?\s*([^():]+?)\s*\)?\s*:\s*\(?\s*([^():]+?)\s*\)?\s*\)', v)
    if m:
        return m.group(2) if CONFIG[m.group(1)] else m.group(3)
    return v


def fld(body, name):
    m = re.search(r'\.' + name + r'\s*=\s*("(?:[^"\\]|\\.)*"|[^,\n]+)', body)
    if not m:
        return None
    v = m.group(1).strip()
    return v[1:-1] if v.startswith('"') else resolve(v)


HG_MOVE_IDS = hg_parse.constants('include/constants/moves.h', 'MOVE_')
HG_MOVE_BY_ID = {}
for k, v in HG_MOVE_IDS.items():
    HG_MOVE_BY_ID.setdefault(v, k)          # primo nome definito (gli alias vengono dopo)
HG_EFFECTS = hg_parse.constants('include/constants/move_effects.h', 'MOVE_EFFECT_')
for _k, _v in hg_parse.constants('include/move_data.h', 'MOVE_EFFECT_').items():
    HG_EFFECTS.setdefault(_k, _v)           # alias definiti in move_data.h
HG_EFFECT_BY_ID = {}
for k, v in HG_EFFECTS.items():
    HG_EFFECT_BY_ID.setdefault(v, k)
HG_RANGES = hg_parse.constants('include/constants/move_effects.h', 'RANGE_')
ENTRIES = move_entries()

# ---------- pokeplatinum ----------
PT_MOVES = lines('generated/moves.txt')
VANILLA_MOVES = PT_MOVES[:PT_MOVES.index('MOVE_SHADOW_FORCE') + 1]
assert len(VANILLA_MOVES) == FIRST_NEW
PT_EFFECTS = lines('generated/move_battle_effects.txt')[:VANILLA_EFFECTS]
PT_RANGES = lines('generated/move_ranges.txt')
RANGE_BY_VALUE = {0: 'RANGE_SINGLE_TARGET'}
for i, r in enumerate(PT_RANGES[1:16]):
    RANGE_BY_VALUE[1 << i] = r
CONTEST_EFFECTS = lines('generated/move_contest_effects.txt')
CONTEST_TYPES = {'CONTEST_COOL': 'CONTEST_TYPE_COOL', 'CONTEST_BEAUTY': 'CONTEST_TYPE_BEAUTY', 'CONTEST_CUTE': 'CONTEST_TYPE_CUTE',
                 'CONTEST_SMART': 'CONTEST_TYPE_SMART', 'CONTEST_TOUGH': 'CONTEST_TYPE_TOUGH'}
APPEALS = hg_parse.constants('include/move_data.h', 'APPEAL_')
CLASSES = {'SPLIT_PHYSICAL': 'CLASS_PHYSICAL', 'SPLIT_SPECIAL': 'CLASS_SPECIAL', 'SPLIT_STATUS': 'CLASS_STATUS'}
FLAGS = {'FLAG_CONTACT': 'MOVE_FLAG_MAKES_CONTACT', 'FLAG_PROTECT': 'MOVE_FLAG_CAN_PROTECT', 'FLAG_MAGIC_COAT': 'MOVE_FLAG_CAN_MAGIC_COAT',
         'FLAG_SNATCH': 'MOVE_FLAG_CAN_SNATCH', 'FLAG_MIRROR_MOVE': 'MOVE_FLAG_CAN_MIRROR_MOVE',
         'FLAG_KEEP_HP_BAR': 'MOVE_FLAG_HIDES_HP_GAUGES', 'FLAG_HIDE_SHADOW': 'MOVE_FLAG_HIDES_SHADOWS'}
PT_TYPES = set(lines('generated/pokemon_types.txt'))

# Animazioni segnaposto: una mossa vanilla per tipo (fisica, speciale); le mosse di stato usano growth / growl.
ANIM_TEMPLATES = {
    'TYPE_NORMAL': ('tackle', 'hyper_voice'), 'TYPE_FIRE': ('fire_punch', 'flamethrower'),
    'TYPE_WATER': ('waterfall', 'water_pulse'), 'TYPE_GRASS': ('razor_leaf', 'energy_ball'),
    'TYPE_ELECTRIC': ('thunder_punch', 'thunderbolt'), 'TYPE_ICE': ('ice_punch', 'ice_beam'),
    'TYPE_FIGHTING': ('karate_chop', 'aura_sphere'), 'TYPE_POISON': ('poison_jab', 'sludge_bomb'),
    'TYPE_GROUND': ('earthquake', 'mud_shot'), 'TYPE_FLYING': ('wing_attack', 'air_slash'),
    'TYPE_PSYCHIC': ('zen_headbutt', 'psychic'), 'TYPE_BUG': ('x_scissor', 'bug_buzz'),
    'TYPE_ROCK': ('rock_slide', 'power_gem'), 'TYPE_GHOST': ('shadow_claw', 'shadow_ball'),
    'TYPE_DRAGON': ('dragon_claw', 'dragon_pulse'), 'TYPE_DARK': ('bite', 'dark_pulse'),
    'TYPE_STEEL': ('iron_head', 'flash_cannon'), 'TYPE_FAIRY': ('sweet_kiss', 'sweet_kiss'),
}


def effect_name(hg_id):
    if hg_id < VANILLA_EFFECTS:
        return PT_EFFECTS[hg_id]
    n = HG_EFFECT_BY_ID.get(hg_id)
    if not n:
        return f'BATTLE_EFFECT_UNUSED_{hg_id}'
    name = 'BATTLE_EFFECT_' + n[len('MOVE_EFFECT_'):]
    # hg-engine riusa nomi che in pokeplatinum indicano già un effetto vanilla diverso (es. HIT_THREE_TIMES)
    return name + '_GEN5' if name in PT_EFFECTS else name


def pt_range(expr):
    names = []
    for part in expr.split('|'):
        v = HG_RANGES[part.strip()]
        names.append(RANGE_BY_VALUE[v])
    return names[0] if len(names) == 1 else names


def stem(move):
    return move[len('MOVE_'):].lower()


def desc_lines(text, where):
    parts = [clean(p, where) for p in re.split(r'\\+[nr]', text or '')]
    return [p + '\n' for p in parts[:-1]] + [parts[-1]]


def convert(official, hg_name):
    b = ENTRIES[hg_name]
    name = clean(fld(b, 'name'), hg_name)
    if len(name) > 12:
        log['long_name'].append(f'{hg_name}: {name}')
    power, acc = int(fld(b, 'power'), 0), int(fld(b, 'accuracy'), 0)
    cls = CLASSES[fld(b, 'split')]
    typ = fld(b, 'type')
    if typ not in PT_TYPES:
        log['type'].append(f'{hg_name}: {typ} -> TYPE_NORMAL')
        typ = 'TYPE_NORMAL'
    eff = HG_EFFECTS[fld(b, 'effect')]
    flags_expr = fld(b, 'flags') or '0'
    flags = []
    for f in re.findall(r'FLAG_\w+', flags_expr):
        if f in FLAGS:
            flags.append(FLAGS[f])
        else:
            log['flag_dropped'].append(f'{hg_name}: {f}')
    if power > 0:
        flags.append('MOVE_FLAG_TRIGGERS_KINGS_ROCK')     # dalla Gen 5 la Roccia di Re vale per tutte le mosse offensive
    order = ['MOVE_FLAG_MAKES_CONTACT', 'MOVE_FLAG_CAN_PROTECT', 'MOVE_FLAG_CAN_MAGIC_COAT', 'MOVE_FLAG_CAN_SNATCH',
             'MOVE_FLAG_CAN_MIRROR_MOVE', 'MOVE_FLAG_TRIGGERS_KINGS_ROCK', 'MOVE_FLAG_HIDES_HP_GAUGES', 'MOVE_FLAG_HIDES_SHADOWS']
    flags = [f for f in order if f in flags]
    appeal = fld(b, 'appeal') or '0'
    appeal = APPEALS.get(appeal, None) if not appeal[0].isdigit() else int(appeal, 0)
    if appeal is None or appeal >= len(CONTEST_EFFECTS) - 1:
        appeal = 0
    data = {
        'name': name,
        'description': desc_lines(fld(b, 'description'), hg_name),
        'class': cls,
        'type': typ,
        'power': power,
        'accuracy': acc,
        'pp': int(fld(b, 'pp'), 0),
        'effect': {'type': effect_name(eff), 'chance': int(fld(b, 'effectChance'), 0)},
        'range': pt_range(fld(b, 'target')),
        'priority': int(fld(b, 'priority'), 0),
        'flags': flags,
        'contest': {'effect': CONTEST_EFFECTS[appeal], 'type': CONTEST_TYPES.get(fld(b, 'contestType'), 'CONTEST_TYPE_COOL')},
    }
    return data, eff


def main():
    new_moves, effects_used = [], collections.defaultdict(list)
    for official in range(FIRST_NEW, LAST_OFFICIAL + 1):
        hg_name = HG_MOVE_BY_ID[official + HG_SHIFT]
        data, eff = convert(official, hg_name)
        new_moves.append((hg_name, data))
        effects_used[eff].append((hg_name, data))
    assert new_moves[0][0] == 'MOVE_HONE_CLAWS' and new_moves[-1][0] == 'MOVE_MALIGNANT_CHAIN', (new_moves[0][0], new_moves[-1][0])

    # elenco mosse
    write('generated/moves.txt', '\n'.join(VANILLA_MOVES + [m for m, _ in new_moves] + ['MAX_MOVES']) + '\n')

    # elenco effetti: stessi numeri di hg-engine
    last_eff = max(HG_EFFECT_BY_ID)
    effects = PT_EFFECTS + [effect_name(i) for i in range(VANILLA_EFFECTS, last_eff + 1)]
    write('generated/move_battle_effects.txt', '\n'.join(effects) + '\n')

    # script degli effetti nuovi (segnaposto finché non vengono portati da hg-engine)
    eff_dir = 'res/battle/scripts/effects'
    hit = open(os.path.join(PP, eff_dir, 'effect_script_0000.s')).read()
    splash = open(os.path.join(PP, eff_dir, 'effect_script_0085.s')).read()
    for i in range(VANILLA_EFFECTS, last_eff + 1):
        path = os.path.join(PP, eff_dir, f'effect_script_{i:04d}.s')
        if os.path.exists(path) and PLACEHOLDER not in open(path).read():
            continue                                    # già portato a mano: non toccare
        users = effects_used.get(i, [])
        damaging = any(d['power'] > 0 for _, d in users) or not users
        body = hit if damaging else splash
        note = f'{PLACEHOLDER}\n@ {effect_name(i)}: ' + (', '.join(m for m, _ in users) or 'no move uses it') + '\n'
        write(os.path.relpath(path, PP), note + body)
        log['effect_placeholder'].append(f'{i} {effect_name(i)} ({len(users)} moves)')
    files = sorted(f for f in os.listdir(os.path.join(PP, eff_dir)) if re.fullmatch(r'effect_script_\d{4}\.s', f))
    write(f'{eff_dir}/meson.build', 'effect_script_files = files(\n' + ',\n'.join(f"    '{f}'" for f in files) + '\n)\n')

    # cartelle delle mosse
    script = open(os.path.join(PP, 'res/moves/absorb/script.s')).read()
    for hg_name, data in new_moves:
        d = os.path.join('res/moves', stem(hg_name))
        rendered = json.dumps(data, indent=4, ensure_ascii=False)
        write(f'{d}/data.json', rendered)
        write(f'{d}/script.s', script)
        anim = os.path.join(PP, d, 'anim.s')
        if not os.path.exists(anim) or PLACEHOLDER in open(anim).read():
            phys, spec = ANIM_TEMPLATES[data['type']]
            if data['class'] == 'CLASS_STATUS':
                tmpl = 'growth' if data['range'] in ('RANGE_USER', 'RANGE_USER_SIDE') else 'growl'
            else:
                tmpl = phys if data['class'] == 'CLASS_PHYSICAL' else spec
            src = open(os.path.join(PP, 'res/moves', tmpl, 'anim.s')).read()
            write(os.path.relpath(anim, PP), src.replace('#include "macros/btlanimcmd.inc"\n',
                  f'#include "macros/btlanimcmd.inc"\n\n{PLACEHOLDER} (copy of {tmpl})\n', 1))

    print(f'mosse nuove: {len(new_moves)} (MAX_MOVES = {FIRST_NEW + len(new_moves)}), effetti: {len(effects)}')
    for k, v in log.items():
        print(f'{k}: {len(v)}')
        for x in v[:8]:
            print('   ', x)
    with open(os.path.join(PP, 'build/import_moves.log'), 'w') as f:
        for k, v in log.items():
            f.write(f'[{k}]\n' + '\n'.join(v) + '\n')


if __name__ == '__main__':
    main()
