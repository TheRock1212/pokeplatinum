"""Porta in pokeplatinum gli script di lotta di hg-engine (effetti 277+, subscript 297+, puntatori 145+).

Platinum e HGSS condividono numerazione di comandi (0-221), effetti (0-276), subscript (0-296),
puntatori dei subscript degli effetti secondari (0-144) e messaggi di lotta (0-1268): hg-engine
aggiunge in coda. Questo script:
  - ricava la corrispondenza dei nomi (costanti e comandi) confrontando gli script vanilla delle due parti;
  - aggiunge in coda a pokeplatinum tutti i subscript e i puntatori di hg-engine con gli stessi numeri;
  - traduce uno script se usa solo comandi esistenti in pokeplatinum, costanti note e subscript a loro
    volta traducibili; altrimenti lo lascia (o lo crea) come segnaposto "@ PLACEHOLDER";
  - accoda alla banca battle_strings i messaggi nuovi di hg-engine che servono.
Non tocca mai uno script che non è più un segnaposto (portato o scritto a mano).
Rieseguibile. Uso: python3 -I port_battle_scripts.py
"""
import collections, glob, json, os, re, sys

sys.path.insert(0, os.path.dirname(__file__))
import hg_parse

PP = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HG = hg_parse.HG
HGB = f'{HG}/data/battle_scripts'
PTB = f'{PP}/res/battle/scripts'
PLACEHOLDER = '@ PLACEHOLDER: generated by tools/expansion/'
VANILLA_EFFECTS, VANILLA_SUBS, VANILLA_PTRS, VANILLA_MSGS = 277, 297, 145, 1269
# Messaggi hg-engine usati dal C portato a mano (le varianti tuo/selvatico/avversario sono consecutive).
C_MESSAGES = [
    1313, 1314, 1315,     # {0}'s {1} raised its {2} drastically!  (abilità)
    1316, 1317, 1318,     # {0}'s {1} rose drastically!
    1520, 1521, 1522,     # {0}'s {1} severely fell!
]
# Costanti che gli script vanilla non usano (quindi non compaiono nella mappa ricavata) ma hanno un equivalente.
ALIASES = {
    'STATUS_BAD_POISON': 'MON_CONDITION_TOXIC',
    'STATUS_POISON': 'MON_CONDITION_POISON',
    'CHECK_OPCODE_HAVE': 'CHECK_HAVE',
    'CHECK_OPCODE_NOT_HAVE': 'CHECK_NOT_HAVE',
    'MULTIHIT_TRIPLE_KICK': 'SYSCTL_TRIPLE_KICK',
    'MULTIHIT_MULTI_HIT_MOVE': 'SYSCTL_MULTI_HIT_MOVE',
}
MSG_COMMANDS = {'PrintMessage': 0, 'PrintGlobalMessage': 0, 'BufferMessage': 0, 'BufferLocalMessage': 1}
log = collections.defaultdict(list)


def read(path):
    return open(path, encoding='utf-8', errors='replace').read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not os.path.exists(path) or read(path) != text:
        open(path, 'w', encoding='utf-8', newline='\n').write(text)


PORTED = '@ PORTED: generated by tools/expansion/port_battle_scripts.py'


def is_placeholder(path):
    """Segnaposto o porting automatico: si può rigenerare. Togliere la prima riga per tenere una modifica a mano."""
    if not os.path.exists(path):
        return True
    t = read(path)
    return PLACEHOLDER in t or t.startswith(PORTED)


def code_lines(text):
    """Righe di codice senza commenti né intestazioni (per confronti e analisi)."""
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    out = []
    for l in text.split('\n'):
        l = re.sub(r'//.*|@.*', '', l).strip()
        if l and not l.startswith(('#', '.include', '.data', '.text')):
            out.append(l)
    return out


TOKEN = re.compile(r'0x[0-9a-fA-F]+|-?\d+|[A-Za-z_]\w*')


def tokens(line):
    return TOKEN.findall(line)


# ---------------------------------------------------------------- hg-engine
def numbered(folder, prefix):
    out = {}
    for p in glob.glob(f'{HGB}/{folder}/{prefix}_*.s'):
        m = re.search(prefix + r'_(\d+)_(\w+)\.s$', os.path.basename(p))
        out[int(m.group(1))] = (m.group(2), p)
    return out


HG_EFFECTS = numbered('effects', 'effect_script')
HG_SUBS = numbered('subscripts', 'subscript')
HG_CONST = read(f'{HG}/include/constants/battle_script_constants.h')
HG_PTRS = {}
for n, v in re.findall(r'#define (MOVE_SUBSCRIPT_PTR_\w+)\s+\(?(\d+)\)?', HG_CONST):
    HG_PTRS.setdefault(int(v), n)
HG_SUB_NAME = {}
for n, v in re.findall(r'#define (BATTLE_SUBSCRIPT_\w+)\s+\(?(\d+)\)?', HG_CONST):
    HG_SUB_NAME.setdefault(int(v), n)
HG_PTR_TABLE = dict(re.findall(r'\[(MOVE_SUBSCRIPT_PTR_\w+)\]\s*=\s*(BATTLE_SUBSCRIPT_\w+)', read(f'{HG}/src/moves.c')))
HG_MSGS = read(f'{HG}/data/text/197.txt').split('\n')

# ---------------------------------------------------------------- pokeplatinum
PT_CMDS = set(re.findall(r'\.macro (\w+)', read(f'{PP}/asm/macros/btlcmd.inc')))
PT_SUB_ORDER = read(f'{PTB}/subscripts/sub_seq.order').split()[:VANILLA_SUBS]
PT_SUB_CONSTS = read(f'{PP}/generated/battle_subscripts.txt').split()[:VANILLA_SUBS]
PT_PTRS = read(f'{PP}/generated/battle_move_subscript_ptrs.txt').split()[:VANILLA_PTRS]
STRINGS_PATH = f'{PP}/res/text/battle_strings.json'
STRINGS = json.load(open(STRINGS_PATH, encoding='utf-8'))
STRINGS['messages'] = STRINGS['messages'][:VANILLA_MSGS] + [m for m in STRINGS['messages'][VANILLA_MSGS:]
                                                            if not m['id'].startswith('BattleStrings_Text_HgEngine')]
PT_IDENTS = set()
for f in glob.glob(f'{PP}/generated/*.txt'):
    PT_IDENTS |= set(read(f).split())
for f in glob.glob(f'{PP}/include/constants/**/*.h', recursive=True) + glob.glob(f'{PP}/include/*.h'):
    PT_IDENTS |= set(re.findall(r'#define\s+(\w+)', open(f, errors='ignore').read()))
    PT_IDENTS |= set(re.findall(r'^\s*([A-Z][A-Z0-9_]+)\s*[=,]', open(f, errors='ignore').read(), re.M))


# ---------------------------------------------------------------- nomi hg -> pt dai file vanilla
def build_namemap():
    pairs = [(HG_EFFECTS[i][1], f'{PTB}/effects/effect_script_{i:04d}.s') for i in range(VANILLA_EFFECTS)]
    pairs += [(HG_SUBS[i][1], f'{PTB}/subscripts/{PT_SUB_ORDER[i]}.s') for i in range(VANILLA_SUBS)]
    votes = collections.defaultdict(collections.Counter)
    for a, b in pairs:
        la, lb = code_lines(read(a)), code_lines(read(b))
        if len(la) != len(lb):
            continue
        for x, y in zip(la, lb):
            tx, ty = tokens(x), tokens(y)
            if len(tx) == len(ty) and tx[0] == ty[0] or (len(tx) == len(ty) and tx[0] not in PT_CMDS):
                for p, q in zip(tx, ty):
                    if not re.fullmatch(r'-?\d+|0x\w+|_\w+', p):
                        votes[p][q] += 1
    m = {}
    for k, c in votes.items():
        best, n = c.most_common(1)[0]
        if n >= 1 and not re.fullmatch(r'-?\d+|0x\w+|_\w+|BattleStrings_\w+', best):
            m[k] = best
    for i in range(VANILLA_SUBS):                        # i subscript vanilla per numero
        m[HG_SUB_NAME[i]] = PT_SUB_CONSTS[i]
    return m


NAMEMAP = build_namemap()


def _unique(name, taken):
    while name in taken:
        name += '_HG'
    return name


# Nomi pokeplatinum dei subscript e dei puntatori nuovi (con _HG se il nome esiste già in pokeplatinum).
_SUB_PT = {i: PT_SUB_CONSTS[i] for i in range(VANILLA_SUBS)}
for _i in sorted(HG_SUBS):
    if _i >= VANILLA_SUBS:
        _SUB_PT[_i] = _unique(HG_SUB_NAME[_i], set(_SUB_PT.values()))
_PTR_PT = {i: PT_PTRS[i] for i in range(VANILLA_PTRS)}
for _i in sorted(HG_PTRS):
    if _i >= VANILLA_PTRS:
        _PTR_PT[_i] = _unique(HG_PTRS[_i], set(_PTR_PT.values()))
# Ogni nome hg-engine (anche gli alias) -> numero -> nome pokeplatinum
HG_SUB_NUM = {n: int(v) for n, v in re.findall(r'#define (BATTLE_SUBSCRIPT_\w+)\s+\(?(\d+)\)?', HG_CONST)}
HG_PTR_NUM = {n: int(v) for n, v in re.findall(r'#define (MOVE_SUBSCRIPT_PTR_\w+)\s+\(?(\d+)\)?', HG_CONST)}


def sub_const(hg_idx):
    return _SUB_PT[hg_idx]


def sub_file(hg_idx):
    return PT_SUB_ORDER[hg_idx] if hg_idx < VANILLA_SUBS else 'subscript_' + _SUB_PT[hg_idx][len('BATTLE_SUBSCRIPT_'):].lower()


# ---------------------------------------------------------------- messaggi
def msg_const(n):
    if n < VANILLA_MSGS:
        return STRINGS['messages'][n]['id']
    ident = f'BattleStrings_Text_HgEngine{n}'
    if not any(m['id'] == ident for m in STRINGS['messages']):
        text = HG_MSGS[n].rstrip('\r').replace('\\n', '\n').replace('\\r', '\r').replace('\\f', '\f')
        parts = re.split(r'(?<=[\n\r\f])', text)
        STRINGS['messages'].append({'id': ident, 'en_US': [p for p in parts if p] or ['']})
        log['messages_added'].append(f'{n}: {text[:50]!r}')
    return ident


# ---------------------------------------------------------------- traduzione
class Untranslatable(Exception):
    pass


def translate(text, where):
    """Script hg-engine -> testo pokeplatinum, o Untranslatable con il motivo."""
    out = ['#include "macros/btlcmd.inc"', '']
    calls = set()
    for raw in text.split('\n'):
        line = raw.rstrip()
        s = line.strip()
        if not s or s.startswith(('#include', '.include', '.data', '.text', '.align')):
            continue
        if s.startswith('//'):
            out.append('    ' + s)
            continue
        code, _, comment = line.partition('//')
        st = code.strip()
        if re.fullmatch(r'_?\w+:', st):
            out.append(st)
            continue
        if not st:
            continue
        cmd = st.split()[0]
        cmd = NAMEMAP.get(cmd, cmd) if cmd not in PT_CMDS else cmd
        if cmd not in PT_CMDS:
            raise Untranslatable(f'command {cmd}')
        args = st[len(st.split()[0]):].strip()
        args = [a.strip() for a in args.split(',')] if args else []
        if cmd in MSG_COMMANDS and len(args) > MSG_COMMANDS[cmd]:
            i = MSG_COMMANDS[cmd]
            try:
                args[i] = msg_const(int(args[i], 0))
            except ValueError:
                raise Untranslatable(f'message {args[i]}')
        new_args = []
        for a in args:
            def repl(m):
                t = m.group(0)
                if re.fullmatch(r'0x[0-9a-fA-F]+|-?\d+', t) or t.startswith('_') or t.startswith('BattleStrings_'):
                    return t
                if t in HG_SUB_NUM:                       # sempre nel namespace di hg-engine
                    calls.add(HG_SUB_NUM[t])
                    return sub_const(HG_SUB_NUM[t])
                if t in HG_PTR_NUM:
                    return _PTR_PT[HG_PTR_NUM[t]]
                if t in ALIASES:
                    return ALIASES[t]
                if t.startswith('ABILITY_') and t not in PT_IDENTS:
                    # abilità che pokeplatinum non ha ancora: nessun Pokémon può averla (rieseguire dopo averle aggiunte)
                    log['ability_missing'].append(f'{where}: {t}')
                    return '0xFFFF'
                if t in ('TRUE', 'FALSE'):
                    return t
                u = NAMEMAP.get(t, t)
                if u not in PT_IDENTS:
                    raise Untranslatable(f'constant {t}')
                return u
            new_args.append(TOKEN.sub(repl, a))
        line_out = '    ' + cmd + (' ' + ', '.join(new_args) if new_args else '')
        if comment.strip():
            line_out += '  // ' + comment.strip()
        out.append(line_out)
    return '\n'.join(out) + '\n', calls


def main():
    # 1. traduzione dei subscript nuovi (punto fisso: un subscript è portabile se lo sono quelli che chiama)
    translated, reasons = {}, {}
    for i in sorted(HG_SUBS):
        if i < VANILLA_SUBS:
            continue
        try:
            translated[i] = translate(read(HG_SUBS[i][1]), HG_SUBS[i][0])
        except Untranslatable as e:
            reasons[i] = str(e)
    changed = True
    while changed:
        changed = False
        for i, (_, calls) in list(translated.items()):
            bad = [c for c in calls if c >= VANILLA_SUBS and c not in translated]
            if bad:
                reasons[i] = f'calls {HG_SUB_NAME[bad[0]]}'
                del translated[i]
                changed = True

    # 2. file dei subscript, ordine del NARC, costanti
    order = list(PT_SUB_ORDER)
    consts = list(PT_SUB_CONSTS)
    for i in sorted(HG_SUBS):
        if i < VANILLA_SUBS:
            continue
        assert i == len(order), f'buco nei subscript hg-engine a {i}'
        order.append(sub_file(i))
        consts.append(sub_const(i))
        path = f'{PTB}/subscripts/{sub_file(i)}.s'
        if not is_placeholder(path):
            continue
        if i in translated:
            write(path, f'{PLACEHOLDER.replace("PLACEHOLDER", "PORTED")}port_battle_scripts.py from hg-engine {HG_SUBS[i][0]}\n'
                  + translated[i][0])
            log['subscript_ported'].append(HG_SUB_NAME[i])
        else:
            write(path, f'{PLACEHOLDER}port_battle_scripts.py ({reasons[i]})\n#include "macros/btlcmd.inc"\n\n_000:\n    End\n')
            log['subscript_placeholder'].append(f'{HG_SUB_NAME[i]}: {reasons[i]}')
    for f in glob.glob(f'{PTB}/subscripts/subscript_*.s'):       # file generati da esecuzioni precedenti e non più usati
        if os.path.basename(f)[:-2] not in order and is_placeholder(f):
            os.remove(f)
    write(f'{PTB}/subscripts/sub_seq.order', '\n'.join(order) + '\n')
    write(f'{PP}/generated/battle_subscripts.txt', '\n'.join(consts) + '\n')
    write(f'{PTB}/subscripts/meson.build', "sub_seq_narc_order = files('sub_seq.order')\n\nsubscript_files = files(\n"
          + ',\n'.join(f"    '{n}.s'" for n in order) + ',\n)\n')

    # 3. puntatori degli effetti secondari
    ptrs = [_PTR_PT[i] for i in range(max(HG_PTRS) + 1)]
    write(f'{PP}/generated/battle_move_subscript_ptrs.txt', '\n'.join(ptrs) + '\n')
    hpath = f'{PP}/include/data/move_side_effect_subscripts.h'
    h = read(hpath)
    h = re.sub(r'\n    // hg-engine.*?(?=\n};)', '', h, flags=re.S)
    rows = []
    for n in range(VANILLA_PTRS, max(HG_PTRS) + 1):
        target = HG_PTR_TABLE.get(HG_PTRS[n])
        if target is None:
            continue
        rows.append(f'    [{_PTR_PT[n]}] = {sub_file(HG_SUB_NUM[target])},')
    h = h.replace('\n};', '\n    // hg-engine (tools/expansion/port_battle_scripts.py)\n' + '\n'.join(rows) + '\n};', 1)
    write(hpath, h)

    # 4. script degli effetti
    for i in sorted(HG_EFFECTS):
        if i < VANILLA_EFFECTS:
            continue
        path = f'{PTB}/effects/effect_script_{i:04d}.s'
        if not is_placeholder(path):
            continue
        try:
            text, calls = translate(read(HG_EFFECTS[i][1]), HG_EFFECTS[i][0])
            bad = [c for c in calls if c >= VANILLA_SUBS and c not in translated]
            if bad:
                raise Untranslatable(f'calls {HG_SUB_NAME[bad[0]]}')
            head = read(path).split('#include')[0] if os.path.exists(path) else ''
            note = '\n'.join(l for l in head.split('\n') if l.startswith('@ BATTLE_EFFECT'))
            write(path, f'@ PORTED: generated by tools/expansion/port_battle_scripts.py from hg-engine {HG_EFFECTS[i][0]}\n'
                  + (note + '\n' if note else '') + text)
            log['effect_ported'].append(f'{i} {HG_EFFECTS[i][0]}')
        except Untranslatable as e:
            log['effect_not_ported'].append(f'{i} {HG_EFFECTS[i][0]}: {e}')

    for n in C_MESSAGES:                         # messaggi usati dal codice C portato a mano
        msg_const(n)
    STRINGS['messages'][VANILLA_MSGS:] = sorted(STRINGS['messages'][VANILLA_MSGS:], key=lambda m: int(m['id'][len('BattleStrings_Text_HgEngine'):]))
    write(STRINGS_PATH, json.dumps(STRINGS, indent=2, ensure_ascii=False) + '\n')

    for k, v in log.items():
        print(f'{k}: {len(v)}')
    reasons_count = collections.Counter(x.split(': ', 1)[1] for x in log['effect_not_ported'])
    print('motivi effetti non portati:', reasons_count.most_common(25))
    with open(f'{PP}/build/port_battle_scripts.log', 'w') as f:
        for k, v in log.items():
            f.write(f'[{k}]\n' + '\n'.join(v) + '\n')


if __name__ == '__main__':
    main()
